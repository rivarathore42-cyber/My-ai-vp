"""Section AA: deployment on Render.com (Phase 11, updated in Phase 12).

The service is a Docker web service built from the repository's Dockerfile. It listens on $PORT on all interfaces, answers
its health check on /health without touching identity or the database, opens straight into the assistant (no pairing),
and starts without any model (the engine says so). The operator token is generated by Render and is never written into
the repository.
"""
import importlib.util
import os
import re
import tempfile
from pathlib import Path

from galaxy import llm as L

ROOT = Path(__file__).resolve().parents[1]


def _load_entry():
    spec = importlib.util.spec_from_file_location("galaxy_run_entry", ROOT / "run.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


async def run(check) -> None:
    blueprint = (ROOT / "render.yaml").read_text(encoding="utf-8")
    check("runtime: docker" in blueprint and "dockerfilePath: ./Dockerfile" in blueprint
          and "healthCheckPath: /health" in blueprint,
          "AA-blueprint: Render builds the root Dockerfile and checks /health")
    check("generateValue: true" in blueprint and "GALAXY_API_TOKEN" in blueprint,
          "AA-blueprint: Render generates the operator token")
    check("GALAXY_AUTH" not in blueprint, "AA-blueprint: no access mode is set; the page opens straight in")
    check(not re.search(r"GALAXY_API_TOKEN\s+value:", blueprint),
          "AA-blueprint: no token value is written in the repository")

    dockerfile = (ROOT / "Dockerfile").read_text(encoding="utf-8")
    check("HOST=0.0.0.0" in dockerfile and "USER user" in dockerfile and "GALAXY_SKIP_LLM=1" in dockerfile
          and 'CMD ["sh", "-c", "python scripts/fetch_model.py; exec python run.py"]' in dockerfile,
          "AA-docker: all interfaces, a non-root user, heuristics by default, a start command")
    check("GALAXY_API_TOKEN=" not in dockerfile and "GALAXY_AUTH" not in dockerfile,
          "AA-docker: no secret and no access mode in the image")
    check("ARG INSTALL_LLM=0" in dockerfile and "|| echo" in dockerfile,
          "AA-docker: the model engine is optional and cannot break the build")
    check((ROOT / "deploy" / "huggingface" / "Dockerfile").is_file()
          and (ROOT / "deploy" / "huggingface" / "README.md").is_file(),
          "AA-docker: the Hugging Face variant is kept in deploy/huggingface")

    entry = _load_entry()
    check(entry.resolve_bind({"PORT": "10001"}) == ("0.0.0.0", 10001),
          "AA-bind: with PORT set the server listens on all interfaces at that port")
    check(entry.resolve_bind({}) == ("127.0.0.1", 8000), "AA-bind: without PORT it stays on loopback")
    check(entry.resolve_bind({"HOST": "10.0.0.5", "PORT": "9"}) == ("10.0.0.5", 9), "AA-bind: an explicit HOST wins")

    api_source = (ROOT / "galaxy" / "api.py").read_text(encoding="utf-8")
    start = api_source.index('@app.get("/health")')
    health = api_source[start:api_source.index('@app.get("/static/voice/', start)]
    check('"alive"' in health and "who(request)" not in health and "service." not in health,
          "AA-health: /health is public and touches neither identity nor the database")

    previous = os.environ.get("GALAXY_SKIP_LLM")
    os.environ["GALAXY_SKIP_LLM"] = "1"
    try:
        provider = L.LocalLLMProvider(model_path=Path(tempfile.mkdtemp()) / "absent.gguf")
        loaded = provider.load()
        check(loaded is False and provider.state == "disabled" and not provider.available(),
              "AA-heuristics: with GALAXY_SKIP_LLM=1 the model is not loaded and the engine says so")
    finally:
        if previous is None:
            os.environ.pop("GALAXY_SKIP_LLM", None)
        else:
            os.environ["GALAXY_SKIP_LLM"] = previous

    requirements = [line.strip() for line in (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines()
                    if line.strip() and not line.strip().startswith("#")]
    check("fastapi" in requirements and "uvicorn" in requirements and not any(r.startswith("llama") for r in requirements),
          "AA-requirements: the runtime is listed; the model engine is optional")
    check("Free hosting" in (ROOT / "galaxy" / "web" / "app.js").read_text(encoding="utf-8"),
          "AA-page: a sleeping free instance is explained on the page")
